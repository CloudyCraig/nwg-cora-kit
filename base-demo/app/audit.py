# Whitelisted strings - any caller passing arbitrary text gets coerced
# back into the closed enum so a log-injection attempt cannot split a
# JSON record by injecting `"` or `\n` (escape=json on the emitter side
# also handles this, but defense in depth).
_KNOWN_TIERS = frozenset({"bronze", "silver", "gold"})
_KNOWN_DECISIONS = frozenset(
    {"accepted", "rejected", "throttled", "review", "error", "unknown"}
)
_KNOWN_DECLINE_REASONS = frozenset(
    {
        "",
        "tier_throttle",
        "fraud_score_high",
        "sanctions_match",
        "insufficient_funds",
        "limit_breach",
        "scheme_unavailable",
        "downstream_error",
        "simulated",
    }
)
_KNOWN_AUTH_OUTCOMES = frozenset(
    {"success", "failed", "logout", "session_expired", "rate_limited"}
)
# Network Information API effective_type closed enum. The W3C spec
# (https://wicg.github.io/netinfo/#dom-effectiveconnectiontype) defines
# exactly these values; everything else gets coerced to "unknown" so a
# malicious caller cannot smuggle arbitrary strings into the audit
# record (codeguard-0-input-validation-injection: positive validation
# at the trust boundary).
_KNOWN_NETWORK_TYPES = frozenset(
    {"slow-2g", "2g", "3g", "4g", "wifi", "ethernet", "unknown"}
)
# Source of the network beacon - "session_start" is fired once at
# initNetworkContext(), "change" on every connection.change callback.
_KNOWN_NETWORK_SOURCES = frozenset({"session_start", "change"})


def _coerce(value: Any, allowed: frozenset[str], default: str) -> str:
    if value is None:
        return default
    s = str(value).strip().lower()
    return s if s in allowed else default


def emit_payment_audit(
    payment_id: str,
    customer_id: str | None,
    customer_tier: str | None,
    scheme: str | None,
    amount_minor_units: int | float | None,
    currency: str | None,
    decision: str,
    decline_reason: str | None = None,
    sanctions_hit: bool = False,
    fraud_score: float | None = None,
    channel: str | None = None,
) -> None:
    """Emit one ``nwpay:payment_audit`` event."""
    payload: dict[str, Any] = {
        "@timestamp": time.strftime(
            "%Y-%m-%dT%H:%M:%S." + f"{int((time.time() % 1) * 1000):03d}Z",
            time.gmtime(),
        ),
        "event_type": "payment_audit",
        "service": SERVICE_NAME,
        "service_tier": SERVICE_TIER,
        "deployment_environment": DEPLOYMENT_ENVIRONMENT,
        "payment_id": str(payment_id),
        "customer_id_hash": redact_customer_id(customer_id),
        "customer_tier": _coerce(customer_tier, _KNOWN_TIERS, "bronze"),
        "scheme": (scheme or "").upper() or None,
        "amount_minor_units": int(amount_minor_units) if amount_minor_units is not None else None,
        "currency": (currency or None),
        "channel": channel or None,
        "decision": _coerce(decision, _KNOWN_DECISIONS, "unknown"),
        "decline_reason": _coerce(
            decline_reason or "", _KNOWN_DECLINE_REASONS, ""
        ) or None,
        "sanctions_hit": bool(sanctions_hit),
        "fraud_score": (
            round(max(0.0, min(1.0, float(fraud_score))), 4)
            if fraud_score is not None
            else None
        ),
        "trace_id": _current_trace_id(),
    }
    _emit({k: v for k, v in payload.items() if v is not None})


def emit_auth_event(
    username: str,
    outcome: str,
    client_ip: str | None = None,
    user_agent: str | None = None,
    mfa: bool = False,
) -> None:
    """Emit one ``nwpay:auth`` event for the SPA login/logout flow.

    Note that ``username`` is treated as a low-sensitivity identifier
    (the demo only has named personas: olivia/james/margaret/admin).
    For any production adoption, hash this the same way as customer_id.
    """
    payload: dict[str, Any] = {
        "@timestamp": time.strftime(
            "%Y-%m-%dT%H:%M:%S." + f"{int((time.time() % 1) * 1000):03d}Z",
            time.gmtime(),
        ),
        "event_type": "auth",
        "service": SERVICE_NAME,
        "service_tier": SERVICE_TIER,
        "deployment_environment": DEPLOYMENT_ENVIRONMENT,
        "username": str(username)[:64] if username else None,
        "outcome": _coerce(outcome, _KNOWN_AUTH_OUTCOMES, "failed"),
        "client_ip": (str(client_ip)[:64] if client_ip else None),
        "user_agent": (str(user_agent)[:256] if user_agent else None),
        "mfa": bool(mfa),
        "trace_id": _current_trace_id(),
    }
    _emit({k: v for k, v in payload.items() if v is not None})


def emit_network_event(
    session_id: str | None,
    customer_id: str | None,
    customer_tier: str | None,
    effective_type: str | None,
    previous_effective_type: str | None,
    downlink_mbps: float | None,
    rtt_ms: int | None,
    save_data: bool,
    source: str,
    client_ip: str | None = None,
    user_agent: str | None = None,
) -> None:
    """Emit one ``event_type=network`` audit event for SPA network state.

    Bridges the browser's view of the network (Network Information API)
    into Splunk Enterprise so ITSI correlation searches can fire on
    intermittent-connectivity signals - the equivalent data is in
    Splunk Observability Cloud (RUM) but not reachable from ITSI today.

    Schema (all closed enums / size caps applied):
      - session_id            opaque RUM session id (<=64 chars)
      - customer_id           HMAC-SHA256 hashed via redact_customer_id
      - customer_tier         coerced to bronze/silver/gold/unknown
      - effective_type        coerced via _KNOWN_NETWORK_TYPES
      - previous_effective_type  coerced via _KNOWN_NETWORK_TYPES
      - downlink_mbps         clamped to [0, 1000]
      - rtt_ms                clamped to [0, 60000]
      - save_data             bool
      - source                "session_start" or "change"
      - client_ip / user_agent  same handling as emit_auth_event

    Cardinality budget: 5 effective_type values * 6 (with from-state) *
    3 tiers ~= 90 distinct (customer_tier, from, to) tuples per source.
    Safe to leave running indefinitely.
    """
    payload: dict[str, Any] = {
        "@timestamp": time.strftime(
            "%Y-%m-%dT%H:%M:%S." + f"{int((time.time() % 1) * 1000):03d}Z",
            time.gmtime(),
        ),
        "event_type": "network",
        "service": SERVICE_NAME,
        "service_tier": SERVICE_TIER,
        "deployment_environment": DEPLOYMENT_ENVIRONMENT,
        "session_id": (str(session_id)[:64] if session_id else None),
        "customer_id_hash": redact_customer_id(customer_id),
        "customer_tier": _coerce(customer_tier, _KNOWN_TIERS, "bronze"),
        "effective_type": _coerce(effective_type, _KNOWN_NETWORK_TYPES, "unknown"),
        "previous_effective_type": (
            _coerce(previous_effective_type, _KNOWN_NETWORK_TYPES, "unknown")
            if previous_effective_type
            else None
        ),
        "downlink_mbps": (
            round(max(0.0, min(1000.0, float(downlink_mbps))), 3)
            if downlink_mbps is not None
            else None
        ),
        "rtt_ms": (
            int(max(0, min(60000, int(rtt_ms))))
            if rtt_ms is not None
            else None
        ),
        "save_data": bool(save_data),
        "source": _coerce(source, _KNOWN_NETWORK_SOURCES, "change"),
        "client_ip": (str(client_ip)[:64] if client_ip else None),
        "user_agent": (str(user_agent)[:256] if user_agent else None),
        "trace_id": _current_trace_id(),
    }
    _emit({k: v for k, v in payload.items() if v is not None})


# ---------------------------------------------------------------------------
# PSD2 Strong Customer Authentication (SCA) event emission.
#
# UK retail banks must produce regulator-ready audit trails for every
# SCA challenge: which method (SMS OTP, push notification, biometric,
# device-bound passkey, hardware token), which RTS exemption (if any),
# and which outcome (passed, failed, abandoned, expired). This helper
# emits the canonical record.
#
# All fields are server-coerced to fixed allow-lists so a malicious
# caller cannot widen the schema or smuggle PII.
# ---------------------------------------------------------------------------

# Closed enums per PSD2 RTS Article 4 (SCA elements) and Articles
# 10-18 (exemptions). Anything outside the list is normalised to a
# safe default; this prevents log-injection from exposing arbitrary
# strings to downstream queries.
_KNOWN_SCA_METHODS = frozenset({
    "sms_otp", "push_notification", "biometric_face",
    "biometric_fingerprint", "passkey", "hardware_token", "card_reader",
})
_KNOWN_SCA_OUTCOMES = frozenset({"passed", "failed", "abandoned", "expired", "challenged"})
_KNOWN_SCA_EXEMPTIONS = frozenset({
    "low_value",                   # RTS Art. 16
    "trusted_beneficiary",         # RTS Art. 13
    "recurring_payment",           # RTS Art. 14
    "corporate_payment",           # RTS Art. 17
    "transaction_risk_analysis",   # RTS Art. 18
    "contactless_low_value",       # RTS Art. 11
    "unattended_terminal",         # RTS Art. 12
})


def emit_sca_event(
    username: str,
    sca_method: str,
    sca_outcome: str,
    sca_exemption: str | None = None,
    challenge_id: str | None = None,
    payment_id: str | None = None,
    risk_score: float | None = None,
    duration_ms: int | None = None,
) -> None:
    """Emit one ``nwpay:auth event_type=sca_challenge`` record.

    Used by the SPA login + payment-initiation flows whenever PSD2
    Strong Customer Authentication is invoked. Closed enums on
    ``sca_method`` / ``sca_outcome`` / ``sca_exemption`` mean a hostile
    caller cannot inject arbitrary values into the regulatory audit
    trail (codeguard-0-input-validation-injection: positive allow-list
    validation at the trust boundary).
    """
    payload: dict[str, Any] = {
        "@timestamp": time.strftime(
            "%Y-%m-%dT%H:%M:%S." + f"{int((time.time() % 1) * 1000):03d}Z",
            time.gmtime(),
        ),
        "event_type": "sca_challenge",
        "service": SERVICE_NAME,
        "service_tier": SERVICE_TIER,
        "deployment_environment": DEPLOYMENT_ENVIRONMENT,
        "username": str(username)[:64] if username else None,
        "sca_method": _coerce(sca_method, _KNOWN_SCA_METHODS, "sms_otp"),
        "sca_outcome": _coerce(sca_outcome, _KNOWN_SCA_OUTCOMES, "failed"),
        # Exemption is optional. Only emit if explicitly invoked AND in
        # the allow-list; otherwise omit (None gets stripped below).
        "sca_exemption": (
            sca_exemption if sca_exemption in _KNOWN_SCA_EXEMPTIONS else None
        ),
        "challenge_id": str(challenge_id)[:64] if challenge_id else str(uuid.uuid4()),
        "payment_id": str(payment_id)[:64] if payment_id else None,
        "risk_score": (
            round(float(risk_score), 4)
            if risk_score is not None and 0.0 <= float(risk_score) <= 1.0
            else None
        ),
        "duration_ms": (
            int(duration_ms)
            if isinstance(duration_ms, int) and 0 <= duration_ms <= 600_000
            else None
        ),
        "trace_id": _current_trace_id(),
    }
    _emit({k: v for k, v in payload.items() if v is not None})


def emit_chaos_event(
    scenario: str,
    target_service: str | None,
    actor: str | None,
    action: str = "inject",
    started_at: float | None = None,
    ended_at: float | None = None,
    details: dict[str, Any] | None = None,
) -> None:
    """Emit one ``nwpay:chaos`` event from scripts/incident.sh.

    ``action`` is "inject" or "clear". The bash hook in
    ``scripts/incident.sh`` prefers a direct HEC POST, but this Python
    helper is provided for parity (and for a future Python-based chaos
    runner).
    """
    payload: dict[str, Any] = {
        "@timestamp": time.strftime(
            "%Y-%m-%dT%H:%M:%S." + f"{int((time.time() % 1) * 1000):03d}Z",
            time.gmtime(),
        ),
        "event_type": "chaos",
        "service": SERVICE_NAME,
        "scenario": str(scenario)[:64],
        "target_service": (str(target_service)[:64] if target_service else None),
        "actor": (str(actor)[:64] if actor else None),
        "action": "clear" if str(action).strip().lower() == "clear" else "inject",
        "started_at": started_at,
        "ended_at": ended_at,
        "event_id": str(uuid.uuid4()),
        "details": details if isinstance(details, dict) else None,
    }
    _emit({k: v for k, v in payload.items() if v is not None})
