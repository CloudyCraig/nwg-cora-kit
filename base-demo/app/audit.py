"""Synthetic banking audit / SPA auth / chaos audit emitter.

Writes structured JSON events to a dedicated audit log file that a
sidecar (`audit-tail`) reads and ships to Splunk Enterprise via the
container stdout pipeline. Per-container splunk.com/sourcetype and
splunk.com/index annotations on the audit-tail sidecar route those
events to ``index=nwpay_audit`` (sourcetypes: ``nwpay:payment_audit``,
``nwpay:auth``, ``nwpay:chaos``) without polluting the main service
log stream that goes to ``index=main``.

Why a separate file instead of stdout?
  * The Splunk OTel collector chart routes container logs by pod or
    per-container annotation, not by log content. Mixing audit events
    into the regular service stdout would force every record from that
    pod into the audit index. A dedicated file picked up by a small
    sidecar lets us route per-container.
  * The file is rotated by Python's logging.handlers.RotatingFileHandler
    so a long-running pod cannot fill the emptyDir.

Privacy / PII (codeguard-0-privacy-data-protection,
codeguard-0-logging "redact/tokenize secrets and sensitive fields"):
  * ``customer_id`` is HMAC-SHA256 tokenized with a server-side pepper
    (``AUDIT_PEPPER`` env, or read from ``AUDIT_PEPPER_PATH`` file -
    Kubernetes Secret mount).
  * Account numbers, names, emails, phone numbers MUST NOT be passed to
    these helpers - the demo's payment payload schema does not include
    them, and ``emit_payment_audit`` does not accept them either, so a
    code reviewer can audit by inspection.
  * The pepper, if present, never enters the log stream and never enters
    a span attribute. The redaction is one-way; the original customer id
    cannot be recovered from the indexed digest.
"""

from __future__ import annotations

import hmac
import json
import logging
import os
import sys
import threading
import time
import uuid
from hashlib import sha256
from logging.handlers import RotatingFileHandler
from typing import Any

# Defer the OpenTelemetry import so this module is testable without the
# heavy SDK installed (the unit test hashes a customer id and exercises
# the JSON serialisation - it should not require splunk-py-trace).
try:
    from opentelemetry import trace as _otel_trace  # type: ignore
except Exception:  # pragma: no cover - SDK absent in unit-test venv
    _otel_trace = None


# ---------------------------------------------------------------------------
# Configuration. Values are looked up once at import time so the runtime
# behaviour is deterministic across the lifetime of the process.
# ---------------------------------------------------------------------------

AUDIT_LOG_PATH = os.environ.get("AUDIT_LOG_PATH", "/var/log/audit/audit.jsonl")
AUDIT_LOG_MAX_BYTES = max(
    1024 * 1024, int(os.environ.get("AUDIT_LOG_MAX_BYTES", str(50 * 1024 * 1024)))
)
AUDIT_LOG_BACKUP_COUNT = max(
    0, int(os.environ.get("AUDIT_LOG_BACKUP_COUNT", "3"))
)

# AUDIT_ENABLED gates ALL emission. Defaults to true; per-pod values.yaml
# can flip this to false on services that should not emit audit events
# (e.g. low-tier infrastructure pods).
AUDIT_ENABLED = os.environ.get("AUDIT_ENABLED", "true").strip().lower() in {
    "1",
    "true",
    "yes",
    "on",
}

SERVICE_NAME = os.environ.get("OTEL_SERVICE_NAME", "unknown-service")
SERVICE_TIER = os.environ.get("SERVICE_TIER", "unknown")
DEPLOYMENT_ENVIRONMENT = os.environ.get("OTEL_RESOURCE_DEPLOYMENT_ENVIRONMENT", "demo")


def _load_pepper() -> bytes:
    """Resolve the HMAC pepper from env / file / fallback.

    Order of precedence:
      1. ``AUDIT_PEPPER_PATH`` - path to a Kubernetes Secret-mounted
         file. Preferred: the pepper never appears in the pod spec.
      2. ``AUDIT_PEPPER`` - environment variable (sensitive).
      3. Fallback: a deterministic per-pod value derived from
         ``HOSTNAME`` and a fixed salt. Logged at WARNING because this
         path is only safe for the demo and breaks redaction stability
         across pod restarts.

    Returns the pepper as bytes (UTF-8 encoded), or a generated bytes
    string for the fallback. Never returns an empty value: an empty
    pepper would silently degrade the HMAC into a known-construction
    SHA-256 prefix attack vector.
    """
    path = os.environ.get("AUDIT_PEPPER_PATH", "").strip()
    if path:
        try:
            with open(path, "rb") as f:
                data = f.read().strip()
            if data:
                return data
        except OSError as exc:  # noqa: BLE001
            logging.getLogger(SERVICE_NAME).warning(
                "audit_pepper_path_unreadable path=%s err=%s", path, exc
            )

    env = os.environ.get("AUDIT_PEPPER", "").strip()
    if env:
        return env.encode("utf-8")

    fallback = (
        f"audit-pepper-fallback:{os.environ.get('HOSTNAME', 'unknown-host')}"
    ).encode("utf-8")
    logging.getLogger(SERVICE_NAME).warning(
        "audit_pepper_fallback_in_use - configure AUDIT_PEPPER_PATH or AUDIT_PEPPER for stable redaction"
    )
    return fallback


_PEPPER: bytes = _load_pepper()


# ---------------------------------------------------------------------------
# Lazy file handler so unit tests that import this module do not fail when
# /var/log/audit does not exist.
# ---------------------------------------------------------------------------

_audit_handler_lock = threading.Lock()
_audit_handler: RotatingFileHandler | None = None
_fallback_to_stdout: bool = False


def _get_audit_handler() -> RotatingFileHandler | None:
    global _audit_handler, _fallback_to_stdout

    with _audit_handler_lock:
        if _audit_handler is not None or _fallback_to_stdout:
            return _audit_handler

        try:
            os.makedirs(os.path.dirname(AUDIT_LOG_PATH), exist_ok=True)
            handler = RotatingFileHandler(
                AUDIT_LOG_PATH,
                maxBytes=AUDIT_LOG_MAX_BYTES,
                backupCount=AUDIT_LOG_BACKUP_COUNT,
                encoding="utf-8",
                delay=True,
            )
            handler.setFormatter(logging.Formatter("%(message)s"))
            _audit_handler = handler
            return handler
        except OSError as exc:  # noqa: BLE001
            logging.getLogger(SERVICE_NAME).warning(
                "audit_log_unwritable path=%s err=%s - falling back to stdout",
                AUDIT_LOG_PATH,
                exc,
            )
            _fallback_to_stdout = True
            return None


def redact_customer_id(customer_id: str | None) -> str | None:
    """One-way HMAC tokenize a customer id with the configured pepper.

    Returns ``None`` if input is ``None`` or empty, otherwise a 32-char
    lowercase hex digest. ``hmac.compare_digest`` would be used for
    verification; this helper is for the emit-side only.

    The output is stable for the lifetime of a pepper. Rotating the
    pepper invalidates historical correlations - acceptable in a demo,
    documented in audit.py header for any prod adopter.
    """
    if customer_id is None:
        return None
    s = str(customer_id).strip()
    if not s:
        return None
    digest = hmac.new(_PEPPER, s.encode("utf-8"), sha256).hexdigest()
    return digest[:32]


def _current_trace_id() -> str | None:
    """Best-effort: pull the active OTel trace id so audit events can be
    pivoted to APM. Returns ``None`` when the SDK is absent or the span
    is not recording (e.g. background thread without context)."""
    if _otel_trace is None:
        return None
    try:
        span = _otel_trace.get_current_span()
        if span is None:
            return None
        ctx = span.get_span_context()
        if ctx is None or not ctx.is_valid:
            return None
        return format(ctx.trace_id, "032x")
    except Exception:  # noqa: BLE001
        return None


def _emit(payload: dict[str, Any]) -> None:
    """Serialize and ship one audit record.

    JSON dumped with ``separators=(",", ":")`` keeps the line compact;
    ``ensure_ascii=False`` preserves Unicode customer names without
    surrogate-pair escaping (these are still allow-listed by the caller
    via ``customer_tier`` / ``decline_reason`` enums).

    Any record whose body would exceed 4 KB is truncated and logged
    with ``"_truncated":true``; this is a defensive ceiling, the real
    payload schema below is well under 1 KB. Truncation prevents one
    misuse from pushing the audit pipeline into log injection territory
    (codeguard-0-logging).
    """
    if not AUDIT_ENABLED:
        return

    line = json.dumps(payload, separators=(",", ":"), ensure_ascii=False)
    if len(line.encode("utf-8")) > 4096:
        # Drop unknown extras; keep core fields. Re-emit with a marker.
        compact = {
            k: payload.get(k)
            for k in (
                "@timestamp",
                "event_type",
                "service",
                "outcome",
                "trace_id",
            )
        }
        compact["_truncated"] = True
        line = json.dumps(compact, separators=(",", ":"), ensure_ascii=False)

    handler = _get_audit_handler()
    if handler is not None:
        try:
            handler.emit(logging.LogRecord(
                name="nwpay.audit",
                level=logging.INFO,
                pathname=__file__,
                lineno=0,
                msg=line,
                args=None,
                exc_info=None,
            ))
            return
        except Exception:  # noqa: BLE001 - never let audit failure crash the flow
            pass

    # Fallback: stdout. The collector pod-level annotation will route
    # this to the wrong index (main, not nwpay_audit), but at least the
    # event survives. Operations gets a loud warning at process start.
    sys.stdout.write(line + "\n")
    sys.stdout.flush()


